import {
  CommandExplanation,
  CommandPlan,
  CommandRequest,
  ErrorDiagnosis,
  SystemContext,
} from '@shellmind/core';
import { IAIProvider } from '../provider.interface.js';
import {
  SHELLMIND_SYSTEM_INSTRUCTION,
  buildDiagnosisPrompt,
  buildExplanationPrompt,
  buildGenerationPrompt,
} from '../prompts.js';

export class OllamaProvider implements IAIProvider {
  public readonly id = 'ollama';
  public readonly name = 'Ollama Local (Offline/Private)';
  private endpoint: string;
  private model: string;

  constructor(options?: { endpoint?: string; model?: string }) {
    this.endpoint = options?.endpoint || 'http://localhost:11434';
    this.model = options?.model || 'llama3:latest';
  }

  public async generateCommand(request: CommandRequest): Promise<CommandPlan> {
    try {
      const prompt = buildGenerationPrompt(request);
      const res = await fetch(`${this.endpoint}/api/generate`, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          model: this.model,
          system: SHELLMIND_SYSTEM_INSTRUCTION,
          prompt,
          format: 'json',
          stream: false,
        }),
      });

      if (!res.ok) {
        throw new Error(`Ollama offline or model not found at ${this.endpoint}`);
      }

      const json = await res.json();
      const parsed = JSON.parse(json.response || '{}');

      return {
        command: parsed.command || 'echo "Local model produced no command"',
        explanation: parsed.explanation || 'Generated by local Ollama model',
        risk: parsed.risk || {
          level: 'SAFE',
          reasons: ['Local offline model inference'],
          requiresTypedConfirmation: false,
        },
        alternatives: parsed.alternatives || [],
      };
    } catch (err) {
      console.warn('[ShellMind Ollama Error - check if `ollama serve` is running]:', err);
      return {
        command: `echo "Ollama is not reachable at ${this.endpoint}. Start Ollama or run 'ai provider set gemini'"`,
        explanation: 'Local Ollama daemon unreachable',
        risk: {
          level: 'SAFE',
          reasons: ['Daemon health check notice'],
          requiresTypedConfirmation: false,
        },
      };
    }
  }

  public async explainCommand(command: string, context?: SystemContext): Promise<CommandExplanation> {
    const prompt = buildExplanationPrompt(command, context);
    try {
      const res = await fetch(`${this.endpoint}/api/generate`, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          model: this.model,
          system: SHELLMIND_SYSTEM_INSTRUCTION,
          prompt,
          format: 'json',
          stream: false,
        }),
      });
      const json = await res.json();
      return JSON.parse(json.response || '{}');
    } catch {
      return {
        command,
        summary: `Local offline explanation for: ${command}`,
        syntaxBreakdown: [],
        risk: { level: 'SAFE', reasons: [], requiresTypedConfirmation: false },
      };
    }
  }

  public async diagnoseError(failedCommand: string, stderr: string, context?: SystemContext): Promise<ErrorDiagnosis> {
    const prompt = buildDiagnosisPrompt(failedCommand, stderr, context);
    try {
      const res = await fetch(`${this.endpoint}/api/generate`, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          model: this.model,
          system: SHELLMIND_SYSTEM_INSTRUCTION,
          prompt,
          format: 'json',
          stream: false,
        }),
      });
      const json = await res.json();
      return JSON.parse(json.response || '{}');
    } catch {
      return {
        failedCommand,
        stderr,
        category: 'other',
        rootCause: 'Failed command in local environment.',
        suggestedFixes: ['Inspect stderr logs above'],
      };
    }
  }
}
